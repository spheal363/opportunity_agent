"""一覧ページから「次に読むリンク」を選ぶ Prompt（#47）。

イベント一覧・カレンダーの本文から取り出したリンクを見せ、
**今回の希望・地域・期間に合いそうなものだけ**を選ばせる。

**URL を書かせない。** 選ぶのは渡した一覧の番号だけ。文字列で書かせると、
存在しない URL を作られる。
"""

from ai.llm import UNTRUSTED_DATA_RULE, untrusted_block

SYSTEM = (
    "あなたはイベント一覧ページから取り出したリンクを見て、"
    "ユーザーの希望に合いそうなものだけを選ぶ担当である。"
    "以下の JSON を 1 つだけ返す。\n"
    "\n"
    "{\n"
    '  "is_listing": bool,     // このページはイベント一覧・カレンダーか\n'
    '  "listing_reason": str,  // そう判断した理由。短く\n'
    '  "picked": [\n'
    "    {\n"
    '      "index": int,     // 渡した一覧の番号。**URL は書かない**\n'
    '      "wish": str,      // どの希望に当たりそうか。希望の文言をそのまま\n'
    '      "reason": str     // なぜ読む価値があるか。短く\n'
    "    }\n"
    "  ]\n"
    "}\n"
    "\n"
    "規則:\n"
    "0. **まず、このページがイベント一覧かを判断する。**"
    "本文の冒頭と、リンクの題名の並びから決める。\n"
    "   - 一覧: そのページ自体が開催予定を並べている"
    "（題名にイベント名・日付・会場が繰り返し出る）\n"
    "   - 一覧ではない: 記事・お知らせ・企業情報で、"
    "**関連記事や他の記事へのリンクが並んでいるだけ**のもの\n"
    "   - **リンクが並んでいることだけを根拠にしない。**"
    "記事の関連記事欄にも同じ形のリンクが並ぶ\n"
    "   - 一覧でなければ `is_listing` を false にし、picked は空配列にする\n"
    "1. **選ぶのは番号だけ。** URL を書かない。渡していない番号を返さない。\n"
    "2. **希望に合いそうなものだけ選ぶ。** 数を埋めない。"
    "当たりが無ければ picked は空配列でよい。\n"
    "3. リンクの題名だけで判断する。**日付・開催地・料金を推測で補わない。**"
    "題名に日付が無いものを「期間外」と決めつけない"
    "（分からないだけなので、他に手がかりが無ければ選んでよい）。\n"
    "4. **希望を言い換えない。** 「ポケモンのイベント」を"
    "「ゲーム開発コンテスト」に読み替えない。\n"
    "5. 明らかに希望と関係ないもの（会員登録、広告、企業情報、"
    "過去の開催レポート）は選ばない。\n"
    "6. 出力は JSON のみ。説明文を付けない。"
) + UNTRUSTED_DATA_RULE


def build_user(
    *,
    wishes: list[str],
    location: str | None,
    window: str | None,
    links: list,
    limit: int,
    excerpt: str = "",
) -> str:
    """一覧のリンクを user メッセージに組み立てる。

    **題名は Web から取った文字列。** 指示が仕込まれうるので囲んで渡す。
    """
    lines = [
        f"今回の希望: {' / '.join(wishes) or '指定なし'}",
        f"活動したい地域: {location or '指定なし'}",
        f"対象期間: {window or '指定なし'}",
        f"選んでよい上限: {limit} 件",
        "",
    ]
    if excerpt:
        # **本文の冒頭。** 一覧か記事かは、ここを読まないと分からない。
        lines += ["", "ページ冒頭:", excerpt, ""]
    lines.append("リンクの一覧:")
    lines += [f"{i}: {link.title or '（題名なし）'}" for i, link in enumerate(links)]
    return untrusted_block("listing_links", "\n".join(lines))
